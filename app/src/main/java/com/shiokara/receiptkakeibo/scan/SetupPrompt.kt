package com.shiokara.receiptkakeibo.scan

/**
 * レシートを送るチャットに、最初に一度だけ送る指示文。
 * 以降はレシートの写真だけを送れば、この約束に沿って家計簿に追記してもらえる。
 * アプリの設定画面で書き換えられる。
 */
object SetupPrompt {
    val DEFAULT = """
        このチャットでは、これから私が送るレシートの写真を家計簿に記録してください。
        写真だけを送ります。届くたびに読み取って家計簿に追記し、追加した行を表で返してください。

        # 家計簿の形式
        列は「日付 / 店舗 / 品目 / カテゴリ / 金額（円） / 支払方法 / 備考」で、1品目を1行にします。
        - 日付は 2026/02/28 の形式
        - 店舗は「ブランド名 支店名」(例: サンプルマート 東京駅前店)。前に記録した店はその表記に合わせる
        - 金額はその品目に実際に払った額(税込・値引き後)。外税のレシートは品目ごとに税込に直す(軽減税率の印がある品目は8%、それ以外は10%)
        - 値引きの行は独立させず、直前の品目から差し引いて備考に「まとめ売り値引-¥22」のように書く
        - 同じ品目を複数買った場合は1行にまとめ、品目名に「（×2）」を付ける
        - 品目の合計がレシートの合計と数円ずれたら、いちばん高い品目で調整して備考に「端数¥1調整」と書く

        # カテゴリ
        食料品、嗜好品、酒類、日用品、外食、趣味、医療費、美容・美容院、交通費、経費、その他

        # 支払方法の表記
        楽天ペイ、QUICPay、PayPay、Edy、楽天Edy、交通系IC、クレジットカード、現金 など。レシートに書かれた決済手段をこの表記に合わせる

        # その他
        - 読み取りに自信がない箇所は、表の下に一言添えてください
        - 「今月の合計」「カテゴリ別」などと頼んだら、それまでの記録から集計してください
        - 「全部の表を出して」と頼んだら、これまでの記録をまとめてExcelファイルで出力してください

        過去の家計簿ファイルを添付した場合は、その続きとして記録してください。
        準備ができたら「準備OK」とだけ返してください。
    """.trimIndent()
}
