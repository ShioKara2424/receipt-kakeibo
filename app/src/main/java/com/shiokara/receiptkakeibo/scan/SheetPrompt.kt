package com.shiokara.receiptkakeibo.scan

/**
 * 共有でレシートを送るときに、画像と一緒に渡す指示文。
 * 共有すると毎回新しいチャットになるため、記録のルールとスプレッドシートの URL を毎回添える。
 * 「{シートURL}」は設定したスプレッドシートの URL に置き換わる。アプリの設定画面で書き換えられる。
 */
object SheetPrompt {
    const val PLACEHOLDER = "{シートURL}"

    val DEFAULT = """
        このファイルと一緒に添付したレシートの画像を読み取り、Google Sheets コネクタで次の家計簿スプレッドシートに追記してください。
        $PLACEHOLDER

        # 追記のしかた
        - シート全体は読まないでください。見出し行と、最後の50行だけを読んで、書式と最近の店舗・カテゴリ・支払方法の表記を確認してください
        - 新しい行はシートの末尾(最後のデータ行の次)に追加してください。合計行は作りません
        - 列は「日付 / 店舗 / 品目 / カテゴリ / 金額（円） / 支払方法 / 備考」で、1品目を1行にする
        - 画像が複数ある場合は、すべてのレシートを記録する

        # 記録のルール
        - 日付は 2026/02/28 の形式
        - 店舗は「ブランド名 支店名」(例: サンプルマート 東京駅前店)。読んだ行に同じ店があればその表記に合わせる
        - 金額はその品目に実際に払った額(税込・値引き後)。外税のレシートは品目ごとに税込に直す(軽減税率の印がある品目は8%、それ以外は10%)
        - 値引きの行は独立させず、直前の品目から差し引いて備考に「まとめ売り値引-¥22」のように書く
        - 同じ品目を複数買った場合は1行にまとめ、品目名に「（×2）」を付ける
        - 品目の合計がレシートの合計と数円ずれたら、いちばん高い品目で調整して備考に「端数¥1調整」と書く
        - カテゴリは、食料品、嗜好品、酒類、日用品、外食、趣味、医療費、美容・美容院、交通費、経費、その他 から選ぶ。読んだ行に同じ品目があれば、そのカテゴリに合わせる
        - 支払方法はレシートに書かれた決済手段を、読んだ行で使っている表記に合わせる

        追記が終わったら、追加した行を表で示してください。読み取りに自信がない箇所があれば一言添えてください。
    """.trimIndent()

    fun build(template: String, sheetUrl: String): String = template.replace(PLACEHOLDER, sheetUrl.trim())
}
